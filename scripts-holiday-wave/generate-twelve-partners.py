def q(value: str) -> str:
    """Escape for single-quoted TypeScript string literals."""
    return value.replace("\\", "\\\\").replace("'", "\\'")


def items_block(rows: list[tuple[str, str, str, str]], heading: str) -> str:
    lines = [f"    itemsHeading: '{heading}',", "    items: ["]
    for img, tag, title, text in rows:
        text_esc = q(text)
        title_esc = q(title)
        lines.append(
            f"""      {{
        img: `${{base}}{img}`,
        tag: '{tag}',
        title: '{title_esc}',
        text: '{text_esc}',
      }},"""
        )
    lines.append("    ],")
    return "\n".join(lines)


